-- Conferência dos relacionamentos
SELECT v.id_veiculo, p.nm_pessoa, e.ds_estado, c.ds_cor,
       f.ds_fabricante, m.ds_modelo, v.nr_placa, v.vl_veiculo
FROM veiculos v
JOIN pessoas p ON p.id_pessoa = v.id_pessoa
JOIN estados e ON e.id_estado = v.id_estado
JOIN cores c ON c.id_cor = v.id_cor
JOIN modelos m ON m.id_modelo = v.id_modelo
JOIN fabricante f ON f.id_fabricante = m.id_fabricante
ORDER BY v.id_veiculo;
