public class Cliente {
    //atributos
    private String nome;
    private String cidade;

    //contrutor
    public Cliente(String nome, String cidade) {
        this.nome = nome;
        this.cidade = cidade;
    }

    //get e setters
    public String getNome() {
        return nome;
    }
    public String getCidade() {
        return cidade;
    }

    //metodos
}
