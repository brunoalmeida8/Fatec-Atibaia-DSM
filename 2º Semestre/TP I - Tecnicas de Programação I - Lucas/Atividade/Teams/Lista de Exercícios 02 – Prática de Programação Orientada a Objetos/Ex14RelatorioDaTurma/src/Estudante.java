public class Estudante {
    //atributos
    private String nome;
    private double nota;

    //construtores
    public Estudante(String nome, double nota) {
        this.nome = nome;
        this.nota = nota;
    }

    //get e setters
    public String getNome() {
        return nome;
    }

    public double getNota() {
        return nota;
    }

    //metodos
}